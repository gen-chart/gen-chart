#!/usr/bin/env node
// Compiles schemas/*.schema.json into a committed standalone ESM validator
// module so runtime validation needs no npm install. Run after any schema
// change; `--check` fails when the committed module drifts from the schemas.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const Ajv2020 = require('ajv/dist/2020.js').default;
const standaloneCode = require('ajv/dist/standalone/index.js').default;

const root = fileURLToPath(new URL('..', import.meta.url));
const outPath = `${root}renderers/shared/generated-validators.mjs`;

const NAMES = ['common', 'cartesian', 'distribution', 'proportion', 'matrix'];
const schemas = Object.fromEntries(NAMES.map((n) =>
  [n, JSON.parse(readFileSync(`${root}schemas/${n}.schema.json`, 'utf8'))]));

const ajv = new Ajv2020({
  strict: true,
  allowUnionTypes: true,
  allErrors: true,
  code: { source: true, esm: true }
});
for (const n of NAMES) ajv.addSchema(schemas[n]);

const code = standaloneCode(ajv, {
  validateCartesian: schemas.cartesian.$id,
  validateDistribution: schemas.distribution.$id,
  validateProportion: schemas.proportion.$id,
  validateMatrix: schemas.matrix.$id
});

if (/require\(|from\s+["']ajv/.test(code)) {
  console.error('generated validator is not standalone: it references ajv runtime modules.');
  console.error('Adjust the schemas to avoid keywords needing runtime helpers.');
  process.exit(1);
}

const banner = `// GENERATED by scripts/generate-validators.mjs — do not edit by hand.\n// Standalone ajv (draft 2020-12) validators; zero runtime dependencies.\n`;
const output = banner + code + '\n';

if (process.argv.includes('--check')) {
  const committed = readFileSync(outPath, 'utf8');
  if (committed !== output) {
    console.error('generated-validators.mjs drifts from schemas/. Run: npm run generate:validators');
    process.exit(1);
  }
  console.log('validators: in sync');
} else {
  writeFileSync(outPath, output);
  console.log(`wrote ${outPath} (${output.length} bytes)`);
}
